"""Framework-independent seams shared by native and future orchestration runtimes."""
from typing import Protocol
from .core import Evidence
from .providers.single_frame_vlm import Interpretation

class Planner(Protocol):
    async def choose(self, context: dict) -> dict: ...

class InspectionTools(Protocol):
    locations: dict
    async def snapshot(self) -> dict: ...
    async def observe(self, camera: str, episode: str) -> tuple[Evidence, Interpretation, dict]: ...
    async def inspect(self, target: str) -> dict: ...
    async def stop(self) -> None: ...
